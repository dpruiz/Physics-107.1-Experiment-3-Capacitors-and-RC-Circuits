# DISCHARGING FUNCTION
# ----------------------------------------------------
def discharging(arr, resistance, resistance_measured, resistor_tolerance, capacitance, capacitance_measured, capacitor_tolerance):
    # Theoretical RC constant calculation
    RC_theory = resistance * capacitance
    RC_measured = resistance_measured * capacitance_measured
    # np.arrange returns an array. first arg is start value, second arg is last value, third arg is step.
    time = np.arange(5, len(arr) * 5 + 5, 5)

    # Initiate dataframe
    data1 = pd.DataFrame({"Voltage": arr})
    V = data1["Voltage"]
    V0 = data1.loc[0, "Voltage"]

    # np.where has a conditional on the first arg. If the the conditial is true, the second arg is returned, if not, the third arg is returned.
    factor = np.where(data1["Voltage"] < 4, 0.001, 0.01)
    factor2 = np.where(resistance_measured < 400, 0.01, 0.1)
    # create relative uncertainty column using multimeter uncertainty
    data1["Voltage_RU"] = (data1["Voltage"] * 0.005 + 4 * factor) / data1["Voltage"]
    V_ru = data1["Voltage_RU"]

    # y = ln(V / V_0). Basically linearize for linear regression
    V0_ru = data1.loc[0, "Voltage_RU"]
    data1["ln(V/V_0)"] = np.log(V / V0)
    V_ln = data1["ln(V/V_0)"]

    # Absolute uncertainty on y incorporating V and V0 uncertainties
    data1["ln_ABS"] = np.sqrt(V_ru**2 + V0_ru**2)
    V_ln_abs = data1["ln_ABS"]
    # Relative uncertainty, if divide by zero replace relative uncertainty with zero.
    data1["ln_RU"] = np.where(
        V_ln != 0,
        V_ln_abs / np.abs(V_ln),
        0.0
    )

    # Linear regression and error analysis, will explain in paper. curve_fit first arg requires the model equation to fit to. second and third arg are axes, fourth arg is defining
    # that the sigma used for weight (weight = 1/sigma^2). This is the absolute uncertainty of the y-value in this case. last arg is saying that this is an actual value, not an
    # arbritary weight
    popt, pcov = curve_fit(line, time, V_ln, sigma=V_ln_abs, absolute_sigma=True)
    # popt is array containing slope and intercept of fitted line
    slope, intercept = popt[0], popt[1]
    # pcov is covariant matrix that contains the variance of slope and intercept on its diagonals. sqrt of variance is standard error
    error_slope, error_intercept = np.sqrt(pcov[0, 0]), np.sqrt(pcov[1, 1])

    # Using discharging formula, experimental RC is the negative inverse of slope
    RC_exp = abs(1 / slope)
    # Standard error of slope serves as its absolute uncertainty
    rel_uncertainty_exp = error_slope / abs(slope)
    # Since we are operating without any other source of error on the slope to get experimental time constant, the relative uncertainty for slope and time constant is equal.
    abs_uncertainty_exp = RC_exp * rel_uncertainty_exp

    # Percent error between theoretical and experimental
    error = abs(RC_theory - RC_exp) / RC_theory
    # Uncertainty from tolerance of components
    rel_uncertainty_theory = np.sqrt(resistor_tolerance**2 + capacitor_tolerance**2)
    abs_uncertainty_theory = RC_theory * rel_uncertainty_theory
    # Uncertainty of measured components
    rel_uncertainty_resistor = (resistance_measured * 0.008 + 4 * factor2) / resistance_measured
    rel_uncertainty_capacitor = (capacitance_measured * 0.008 + 4 * 0.1) / capacitance_measured
    rel_uncertainty_measured = np.sqrt(rel_uncertainty_resistor**2 + rel_uncertainty_capacitor**2)
    abs_uncertainty_measured = RC_measured * rel_uncertainty_measured

    # Goodness of fit. First, redefine y-value for clarity. Then also define the array for y-values predicted by best fit eqn
    y_true = V_ln
    y_pred = slope * time + intercept
    # Explicitly define weights for weighted mean
    weight = 1 / (data1["ln_ABS"]**2)
    # Calculate weighted mean
    weighted_mean_y = np.sum(weight * y_true) / np.sum(weight)

    # Calculated total sum of squares and residual sum of squares. Take the ratio between the two and subtracting from 1 will give the ratio of exact sum of squares and
    # total sum of squares. This is basically saying that if there is less residual or unexplained variance, the more fit the line is. This is R^2.
    ss_res_wls = np.sum(weight * (y_true - y_pred)**2)
    ss_tot_wls = np.sum(weight * (y_true - weighted_mean_y)**2)
    r2_wls = 1 - (ss_res_wls / ss_tot_wls)

    # Plot
    scatter = px.scatter(data1,
                         x=time,
                         y="ln(V/V_0)",
                         error_y="ln_ABS",
                         labels={"x": "Time (s)", "ln(V/V_0)": "k (unitless)"})
    lineity = px.line(x=time,
                      y=slope * time + intercept)

    # Create text for equation of line
    equation_text = (
        f"<b>Fit Equation:</b> y = ({slope:.5f} ± {error_slope:.5f})x + ({intercept:.4f} ± {error_intercept:.4f})<br>"
        f"<b>R<sup>2</sup>:</b> {r2_wls:.4f}"
    )
    # Combine graphs and clean up total graph
    scatter.add_trace(lineity.data[0])
    scatter.update_layout(
        title=dict(
            text=f"Charging Graph Across {resistance} Ω Resistor",
            font=dict(size=24),
            automargin=True
        ),
        xaxis=dict(
            tickmode='linear',
            tick0=5,
            dtick=5,
            title="Time (s)"
        ),
        yaxis=dict(
            title="ln(1 - V/V_inf)"
        ),
        annotations=[
            dict(
                x=0.05,  # Relative X position on graph (0 = far left, 1 = far right)
                y=0.15,  # Relative Y position on graph (0 = bottom, 1 = top)
                xref="paper",
                yref="paper",
                text=equation_text,
                showarrow=False,
                align="left",
                bgcolor="rgba(255, 255, 255, 0.8)",  # Semi-transparent white background
                bordercolor="black",
                borderwidth=1,
                borderpad=8,
                font=dict(size=13, color="black")
            )
        ]
    )

    # Combine scatter and line plots. Format graph
    scatter.add_trace(lineity.data[0])
    scatter.update_layout(title=f"Discharging Graph Across {resistance} Ω Resistor")
    scatter.show()

    # Show answers
    print(f"[Discharging] Line: y = {slope:.5f}x + {intercept:.5f}")
    print(f"RC_exp: {RC_exp:.2f} s ± {abs_uncertainty_exp:.2f} s | RC_theory: {RC_theory:.2f} s | R^2: {r2_wls:.4f}\n")

    #check whether experiment is accurate by determining if the greater value of the two minimums are lesser than the lesser value of the
    #two maximums.

    RC_theory_max = RC_theory + abs_uncertainty_theory
    RC_theory_min = RC_theory - abs_uncertainty_theory
    RC_measured_max = RC_measured + abs_uncertainty_measured
    RC_measured_min = RC_measured - abs_uncertainty_measured
    RC_exp_max = RC_exp + abs_uncertainty_exp
    RC_exp_min = RC_exp - abs_uncertainty_exp

    print(f"By checking whether percent error of time constant and experimental relative uncertainty of time constant overlap:")
    if max(RC_theory_min, RC_exp_min) <= min(RC_theory_max, RC_exp_max):
      print("This experiment setup aligns with the theory.\n")
    else:
      print("This experiment setup does not align with the theory.\n")

    print(f"By checking whether measured time constant relative uncertainty and experimental relative uncertainty of time constant overlap:")
    if max(RC_measured_min, RC_exp_min) <= min(RC_measured_max, RC_exp_max):
      print("This experiment setup aligns with the theory.\n")
    else:
      print("This experiment setup does not align with the theory.\n")
    return data1

